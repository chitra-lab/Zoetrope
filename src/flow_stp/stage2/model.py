"""Stage 2 dynamics model on a frozen anatomical axis.

Stage 1 supplies a fixed anatomical coordinate z. Stage 2 learns

    V(z, t)                         velocity
    q(z, t) >= 0                    local developmental source
    F(a, t)                         flow generated by V
    rho(z, t)                       spatiotemporal potential

with

    dF(a,t)/dt = V(F(a,t), t),  F(a,0) = a

and

    partial_t rho + V partial_z rho = q.

The initial condition is spatially constant:

    rho(z,0) = rho_initial

with rho_initial=0 by default. No condition q(z,0)=0 is imposed.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Mapping, Optional, Sequence, Tuple

import torch
import torch.nn as nn
import torch.nn.functional as F


Tensor = torch.Tensor


def as_col(x: Tensor) -> Tensor:
    """Return ``x`` with shape ``[B, 1]``."""
    if x.ndim == 1:
        return x[:, None]
    if x.ndim == 2 and x.shape[1] == 1:
        return x
    raise ValueError(f"Expected shape [B] or [B,1], got {tuple(x.shape)}")


class MLP(nn.Module):
    """Small fully connected network used for the learned fields and decoder."""

    def __init__(
        self,
        in_dim: int,
        out_dim: int,
        hidden: Sequence[int] = (128, 128),
        activation: str = "tanh",
    ) -> None:
        super().__init__()

        activations = {
            "tanh": nn.Tanh,
            "gelu": nn.GELU,
            "relu": nn.ReLU,
            "silu": nn.SiLU,
        }
        if activation not in activations:
            raise ValueError(f"Unknown activation: {activation}")

        act = activations[activation]
        layers = []
        previous = int(in_dim)

        for width in hidden:
            layers.extend((nn.Linear(previous, int(width)), act()))
            previous = int(width)

        layers.append(nn.Linear(previous, int(out_dim)))
        self.net = nn.Sequential(*layers)

    def forward(self, x: Tensor) -> Tensor:
        return self.net(x)


def final_linear_layer(network: nn.Module) -> nn.Linear:
    """Return the final ``nn.Linear`` layer in a network."""

    linear_layers = [
        module
        for module in network.modules()
        if isinstance(module, nn.Linear)
    ]

    if not linear_layers:
        raise RuntimeError(
            "The requested network contains no nn.Linear layers."
        )

    return linear_layers[-1]


@dataclass(frozen=True)
class Stage2Config:
    """Configuration for :class:`Stage2DynamicsModel`."""

    num_genes: int
    field_hidden: Tuple[int, ...] = (128, 128)
    decoder_hidden: Tuple[int, ...] = (128, 128)
    n_flow_steps: int = 24

    # Constant initial condition rho(z,0)=rho_initial.
    rho_initial: float = 0.0

    # Direct V can move characteristics outside [0,1]. Clipping is disabled
    # by default so that it does not silently alter the specified ODE.
    clip_state_to_unit_interval: bool = False
    clamp_eps: float = 1e-5

    # Null-dynamics defaults validated by the static-atlas control.
    #
    # Among transcriptionally equivalent solutions, prefer the
    # minimum-movement solution.
    velocity_penalty_weight: float = 1.0

    # q remains unregularized by default, matching the validated
    # static-atlas experiment.
    source_penalty_weight: float = 0.0

    # Initialize the identity-flow solution exactly.
    zero_initialize_velocity: bool = True

    # Initialize the ReLU source near zero while retaining an active
    # gradient path through the output ReLU.
    q_initial_bias: float = 1e-3
    q_initial_weight_std: float = 1e-3


class Stage2DynamicsModel(nn.Module):
    """Learn dynamics on frozen Stage 1 anatomical coordinates."""

    def __init__(self, config: Stage2Config) -> None:
        super().__init__()
        self.config = config

        if config.num_genes <= 0:
            raise ValueError("num_genes must be positive.")
        if config.n_flow_steps <= 0:
            raise ValueError("n_flow_steps must be positive.")
        if not 0.0 <= config.clamp_eps < 0.5:
            raise ValueError("clamp_eps must lie in [0, 0.5).")
        if config.velocity_penalty_weight < 0.0:
            raise ValueError(
                "velocity_penalty_weight must be nonnegative."
            )
        if config.source_penalty_weight < 0.0:
            raise ValueError(
                "source_penalty_weight must be nonnegative."
            )
        if config.q_initial_weight_std < 0.0:
            raise ValueError(
                "q_initial_weight_std must be nonnegative."
            )

        # Direct velocity parameterization V(z,t)=NN_V(z,t).
        self.v_net = MLP(
            in_dim=2,
            out_dim=1,
            hidden=config.field_hidden,
            activation="tanh",
        )

        # Initialize the identity-flow solution exactly. Only the
        # final layer is zeroed, so V can become nonzero when the
        # data provide sufficient evidence.
        if config.zero_initialize_velocity:
            velocity_final_layer = final_linear_layer(self.v_net)
            nn.init.zeros_(velocity_final_layer.weight)

            if velocity_final_layer.bias is not None:
                nn.init.zeros_(velocity_final_layer.bias)

        # Nonnegative source q(z,t)=ReLU(NN_q(z,t)).
        # ReLU hidden layers match the validated notebook model.
        self.q_net = MLP(
            in_dim=2,
            out_dim=1,
            hidden=config.field_hidden,
            activation="relu",
        )

        source_final_layer = final_linear_layer(self.q_net)

        nn.init.normal_(
            source_final_layer.weight,
            mean=0.0,
            std=config.q_initial_weight_std,
        )

        if source_final_layer.bias is not None:
            nn.init.constant_(
                source_final_layer.bias,
                config.q_initial_bias,
            )

        # Design-document-style decoder log(mu_g)=A_g(z,rho).
        self.expression_decoder = MLP(
            in_dim=2,
            out_dim=config.num_genes,
            hidden=config.decoder_hidden,
            activation="gelu",
        )

    @staticmethod
    def _check_matching_rows(x: Tensor, y: Tensor) -> None:
        if x.shape[0] != y.shape[0]:
            raise ValueError(
                f"Batch-size mismatch: {x.shape[0]} versus {y.shape[0]}."
            )

    def _maybe_clip_state(self, z: Tensor) -> Tensor:
        if not self.config.clip_state_to_unit_interval:
            return z
        eps = self.config.clamp_eps
        return z.clamp(eps, 1.0 - eps)

    # ------------------------------------------------------------------
    # Learned fields
    # ------------------------------------------------------------------

    def velocity(self, z: Tensor, t: Tensor) -> Tensor:
        """Evaluate the unconstrained velocity field ``V(z,t)``."""
        z = as_col(z)
        t = as_col(t)
        self._check_matching_rows(z, t)
        return self.v_net(torch.cat((z, t), dim=1))

    def q(self, z: Tensor, t: Tensor) -> Tensor:
        """Evaluate ``q(z,t)>=0`` with an exact-zero-capable ReLU."""
        z = as_col(z)
        t = as_col(t)
        self._check_matching_rows(z, t)

        raw_q = self.q_net(
            torch.cat((z, t), dim=1)
        )

        return F.relu(raw_q)

    def rho0(self, z: Tensor) -> Tensor:
        """Return the fixed spatially constant initial condition."""
        z = as_col(z)
        return torch.full_like(z, self.config.rho_initial)

    # ------------------------------------------------------------------
    # Flow and characteristic integration
    # ------------------------------------------------------------------

    def inverse_reference_and_rho(
        self,
        z: Tensor,
        t: Tensor,
    ) -> Tuple[Tensor, Tensor]:
        """Return ``a=F^{-1}(z,t)`` and ``rho(z,t)``.

        A fixed-step explicit midpoint method integrates the characteristic
        backward from ``(z,t)`` to time zero while accumulating the source:

            rho(z,t) = rho_initial + integral_0^t q(F(a,s),s) ds.
        """
        z = as_col(z)
        t = as_col(t)
        self._check_matching_rows(z, t)

        x = z
        source_integral = torch.zeros_like(z)
        h = t / self.config.n_flow_steps

        for step in range(self.config.n_flow_steps):
            s = t - step * h

            v_start = self.velocity(x, s)
            x_mid = self._maybe_clip_state(x - 0.5 * h * v_start)
            s_mid = (s - 0.5 * h).clamp(0.0, 1.0)

            source_integral = source_integral + h * self.q(x_mid, s_mid)
            x = self._maybe_clip_state(x - h * self.velocity(x_mid, s_mid))

        a = x
        rho = self.rho0(a) + source_integral
        return a, rho

    def flow_forward(self, a: Tensor, t: Tensor) -> Tensor:
        """Derive ``F(a,t)`` with the fixed-step explicit midpoint method."""
        a = as_col(a)
        t = as_col(t)
        self._check_matching_rows(a, t)

        x = a
        h = t / self.config.n_flow_steps

        for step in range(self.config.n_flow_steps):
            s = step * h

            v_start = self.velocity(x, s)
            x_mid = self._maybe_clip_state(x + 0.5 * h * v_start)
            s_mid = (s + 0.5 * h).clamp(0.0, 1.0)

            x = self._maybe_clip_state(x + h * self.velocity(x_mid, s_mid))

        return x

    def rho_from_reference(
        self,
        a: Tensor,
        t: Tensor,
    ) -> Tuple[Tensor, Tensor]:
        """Return ``F(a,t)`` and the corresponding STP along the characteristic."""
        a = as_col(a)
        t = as_col(t)
        self._check_matching_rows(a, t)

        x = a
        source_integral = torch.zeros_like(a)
        h = t / self.config.n_flow_steps

        for step in range(self.config.n_flow_steps):
            s = step * h

            v_start = self.velocity(x, s)
            x_mid = self._maybe_clip_state(x + 0.5 * h * v_start)
            s_mid = (s + 0.5 * h).clamp(0.0, 1.0)

            source_integral = source_integral + h * self.q(x_mid, s_mid)
            x = self._maybe_clip_state(x + h * self.velocity(x_mid, s_mid))

        return x, self.rho0(a) + source_integral

    # ------------------------------------------------------------------
    # Expression model and objective
    # ------------------------------------------------------------------

    def decode_log_mean(
        self,
        z: Tensor,
        rho: Tensor,
        log_library_size: Optional[Tensor] = None,
    ) -> Tensor:
        """Decode gene-expression log means from ``(z,rho)``."""
        z = as_col(z)
        rho = as_col(rho)
        self._check_matching_rows(z, rho)

        log_mu = self.expression_decoder(torch.cat((z, rho), dim=1))
        if log_library_size is not None:
            log_mu = log_mu + as_col(log_library_size)
        return log_mu

    def forward(
        self,
        z: Tensor,
        time: Tensor,
        log_library_size: Optional[Tensor] = None,
    ) -> Dict[str, Tensor]:
        """Evaluate Stage 2 for frozen Stage 1 coordinates."""
        z = as_col(z)
        time = as_col(time)
        self._check_matching_rows(z, time)

        a, rho = self.inverse_reference_and_rho(z, time)
        log_mu = self.decode_log_mean(z, rho, log_library_size)

        return {
            "z": z,
            "a": a,
            "rho": rho,
            "log_mu": log_mu,
            "mu": torch.exp(log_mu),
        }

    @staticmethod
    def poisson_nll(
        counts: Tensor,
        log_mu: Tensor,
        full: bool = True,
    ) -> Tensor:
        """Mean Poisson negative log likelihood."""
        return F.poisson_nll_loss(
            input=log_mu,
            target=counts.float(),
            log_input=True,
            full=full,
            reduction="mean",
        )

    def loss(
        self,
        batch: Mapping[str, Tensor],
    ) -> Tuple[Tensor, Dict[str, Tensor]]:
        """Compute the Stage 2 Poisson objective and basic diagnostics."""
        output = self.forward(
            z=batch["z"],
            time=batch["time"],
            log_library_size=batch.get("log_library_size"),
        )
        data_loss = self.poisson_nll(
            batch["counts"],
            output["log_mu"],
        )

        velocity_values = self.velocity(
            batch["z"],
            batch["time"],
        )

        source_values = self.q(
            batch["z"],
            batch["time"],
        )

        # Quadratic movement/friction cost.
        velocity_penalty = (
            velocity_values
            .square()
            .mean()
        )

        # Included for optional future experiments. Its default
        # weight is zero, matching the validated control.
        source_penalty = source_values.mean()

        total_loss = (
            data_loss
            + self.config.velocity_penalty_weight
            * velocity_penalty
            + self.config.source_penalty_weight
            * source_penalty
        )

        diagnostics = {
            "total": total_loss.detach(),
            "data": data_loss.detach(),
            "velocity_penalty": velocity_penalty.detach(),
            "weighted_velocity_penalty": (
                self.config.velocity_penalty_weight
                * velocity_penalty
            ).detach(),
            "source_penalty": source_penalty.detach(),
            "weighted_source_penalty": (
                self.config.source_penalty_weight
                * source_penalty
            ).detach(),
            "velocity_mean": velocity_values.mean().detach(),
            "velocity_mean_absolute": (
                velocity_values.abs().mean().detach()
            ),
            "velocity_mean_squared": velocity_penalty.detach(),
            "source_mean": source_values.mean().detach(),
            "z_mean": output["z"].mean().detach(),
            "a_mean": output["a"].mean().detach(),
            "rho_mean": output["rho"].mean().detach(),
            "rho_min": output["rho"].min().detach(),
        }

        return total_loss, diagnostics
