def flow_map(
    a: np.ndarray | float,
    t: np.ndarray | float,
    config: SimulationConfig,
) -> np.ndarray:
    """Prescribed Lagrangian flow F(a,t)=a+U*t."""
    a_array, t_array = np.broadcast_arrays(
        np.asarray(a, dtype=float),
        np.asarray(t, dtype=float),
    )

    return (
        a_array
        + config.flow_speed * t_array
    )


def prescribed_velocity(
    z: np.ndarray | float,
    t: np.ndarray | float,
    config: SimulationConfig,
) -> np.ndarray:
    """Eulerian velocity derived from F: V=dF/dt=U."""
    z_array, t_array = np.broadcast_arrays(
        np.asarray(z, dtype=float),
        np.asarray(t, dtype=float),
    )

    return np.full(
        z_array.shape,
        config.flow_speed,
        dtype=float,
    )


def prescribed_rho(
    z: np.ndarray | float,
    t: np.ndarray | float,
    config: SimulationConfig,
) -> np.ndarray:
    """Prescribed rho(z,t)=A*t+B*z*t+C*t^2."""
    z_array, t_array = np.broadcast_arrays(
        np.asarray(z, dtype=float),
        np.asarray(t, dtype=float),
    )

    return (
        config.rho_time_linear * t_array
        + config.rho_space_time
        * z_array
        * t_array
        + config.rho_time_quadratic
        * t_array**2
    )


def prescribed_q(
    z: np.ndarray | float,
    t: np.ndarray | float,
    config: SimulationConfig,
) -> np.ndarray:
    """Material derivative q=partial_t(rho)+V*partial_z(rho)."""
    z_array, t_array = np.broadcast_arrays(
        np.asarray(z, dtype=float),
        np.asarray(t, dtype=float),
    )

    return (
        config.rho_time_linear
        + config.rho_space_time * z_array
        + (
            2.0 * config.rho_time_quadratic
            + config.flow_speed
            * config.rho_space_time
        )
        * t_array
    )


